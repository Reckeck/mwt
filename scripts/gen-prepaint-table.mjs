// Generates the pre-paint table (background + mode per built-in theme, TP5) from the theme data:
// src/shared/lib/theme/prepaint-table.ts and the marked block of the inline script in index.html.
// Run: node scripts/gen-prepaint-table.mjs
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { build } from 'esbuild'

const root = resolve(import.meta.dirname, '..')
const tableFile = join(root, 'src/shared/lib/theme/prepaint-table.ts')
const htmlFile = join(root, 'index.html')
const START = '// prepaint-table:start (generated by scripts/gen-prepaint-table.mjs)'
const END = '// prepaint-table:end'

const workDir = mkdtempSync(join(tmpdir(), 'prepaint-'))
let themes
try {
  const bundle = join(workDir, 'registry.mjs')
  await build({
    entryPoints: [join(root, 'src/shared/lib/theme/registry.ts')],
    bundle: true,
    format: 'esm',
    outfile: bundle,
    logLevel: 'error',
  })
  themes = (await import(pathToFileURL(bundle).href)).builtinThemes
} finally {
  rmSync(workDir, { recursive: true, force: true })
}

const table = Object.fromEntries(themes.map((theme) => [theme.id, [theme.tokens['--background'].toLowerCase(), theme.mode]]))
const json = JSON.stringify(table)

writeFileSync(
  tableFile,
  `// Generated by scripts/gen-prepaint-table.mjs from the built-in themes: do not edit by hand.
// check-ui-ignore raw-color: the pre-paint table is generated token data, not UI
import type { ThemeMode } from './types'

/** Canvas colour (\`--background\`) and mode of every built-in theme, read by the inline script in index.html (TP5). */
export const PREPAINT_TABLE: Readonly<Record<string, readonly [string, ThemeMode]>> = ${json}
`,
)

const html = readFileSync(htmlFile, 'utf8')
const block = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}[\\s\\S]*?${END}`)
if (!block.test(html)) throw new Error('index.html has no prepaint-table markers')
writeFileSync(htmlFile, html.replace(block, () => `${START}\n          const TABLE = ${json}\n          ${END}`))
