// Rules for markup that overflows, hides actions from a finger, or drifts
// from the shared scale (rules 15-17, references/stable-layout.md).
import { classAttrs, openTags } from './lib.mjs'

/** Sum of the fixed tracks of a `grid-cols-[…]` template, in rem. */
function fixedTracksRem(template) {
  let rem = 0
  for (const track of template.split('_')) {
    const value = track.match(/^(\d+(?:\.\d+)?)(rem|px)$/)
    if (value) rem += value[2] === 'rem' ? Number(value[1]) : Number(value[1]) / 16
  }
  return rem
}

