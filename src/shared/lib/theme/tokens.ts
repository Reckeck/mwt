export type ThemeToken = (typeof THEME_TOKENS)[number]

/** TK2: a theme must give a value to every whitelisted token. */
export function assertCompleteTheme(theme: { id: string; tokens: Partial<Record<string, string>> }): void {
  for (const token of THEME_TOKENS) {
    if (!theme.tokens[token]) {
      throw new Error(`Theme "${theme.id}" is missing token ${token}`)
    }
  }
}
