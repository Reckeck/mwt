//! The chain of frozen payload schemas, composed once.
//!
//! A payload stored at an older version is parsed with the frozen schema of
//! that version and walked up one step at a time, each step the hand-written
//! `From` of a `vN` module. Everything around those steps is the same for
//! every version — the parse, the walk, the refusal of a version from the
//! future, the `doc.version` invariant — and used to be a hand-nested
//! expression in `decode_versioned`, where a forgotten step would quietly
//! skip a version.
//!
//! Here it is generated from one listing ([`schema_chain!`] at the bottom of
//! this file), and the order of the steps is checked by the compiler through
//! [`Legacy::Next`]: a schema can only point at a schema that itself knows
//! the way up. Adding a version is one line in that listing; the work of the
//! migration stays where it belongs, in the frozen module.

use serde::de::DeserializeOwned;

use crate::model::vault::VaultDoc;

/// A frozen payload schema and what it becomes one step up.
pub trait Legacy: DeserializeOwned {
    /// The next schema in the chain; the live [`VaultDoc`] for the last step.
    type Next: From<Self> + Climb;
    /// The `version` a payload of this schema carries on disk.
    const VERSION: u32;
}

/// Walking a parsed payload up to the live document, step by step.
///
/// Implemented here for [`VaultDoc`] (already there, nothing to do) and by
/// [`schema_chain!`] for every schema in its listing.
pub trait Climb {
    fn climb(self) -> VaultDoc;
}

impl Climb for VaultDoc {
    fn climb(self) -> VaultDoc {
        self
    }
}

/// Compose the migration chain from a listing of versions, newest first.
///
/// Generates, for each legacy schema, the one-step walk up through
/// [`Legacy::Next`], and for the whole listing the `upgrade` function that
/// [`super::decode_versioned`] calls: the per-version parse (a payload that
/// does not fit its own schema is [`Error::IncompatibleVault`]), the walk,
/// the refusal of an unknown or future version ([`Error::Unsupported`]) and
/// the invariant that what comes out is a document of the current version.
///
/// [`Error::IncompatibleVault`]: crate::error::Error::IncompatibleVault
/// [`Error::Unsupported`]: crate::error::Error::Unsupported
macro_rules! schema_chain {
    (
        current: $current:ty = $current_version:path,
        $($version:literal => $schema:ty),+ $(,)?
    ) => {
        $(
            // The listing and the schema must agree on the version, or a file
            // would be parsed with the wrong one.
            const _: () = assert!(
                $version == <$schema as $crate::storage::chain::Legacy>::VERSION,
                "a version in schema_chain! is not the schema's own VERSION",
            );

            impl $crate::storage::chain::Climb for $schema {
                fn climb(self) -> $current {
                    <$schema as $crate::storage::chain::Legacy>::Next::from(self).climb()
                }
            }
        )+

        /// Parse a payload stored at `version` and migrate it up to the
        /// current schema. Generated by `schema_chain!`.
        pub(super) fn upgrade(
            version: u32,
            bytes: &[u8],
            fmt: $crate::storage::SnapshotFormat,
        ) -> $crate::error::Result<$current> {
            const CURRENT: u32 = $current_version;
            /// A payload claiming a known version but not fitting its schema.
            fn unfit(err: $crate::error::Error) -> $crate::error::Error {
                $crate::error::Error::IncompatibleVault(err.to_string())
            }
            let doc = match version {
                CURRENT => $crate::storage::parse::<$current>(bytes, fmt).map_err(unfit)?,
                $(
                    $version => $crate::storage::chain::Climb::climb(
                        $crate::storage::parse::<$schema>(bytes, fmt).map_err(unfit)?,
                    ),
                )+
                _ => return Err($crate::error::Error::Unsupported),
            };
            // A step that forgot to move the version up would hand the app a
            // document it cannot save.
            if doc.version != CURRENT {
                return Err($crate::error::Error::Unsupported);
            }
            Ok(doc)
        }
    };
}

schema_chain! {
    current: VaultDoc = crate::VAULT_FORMAT_VERSION,
    2 => super::v2::VaultDocV2,
    1 => super::v1::VaultDocV1,
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::error::Error;
    use crate::storage::SnapshotFormat;

    /// A synthetic chain of two steps on top of the live document, so a walk
    /// that went straight to the current schema instead of through every
    /// step is visible in what comes out.
    #[derive(serde::Deserialize)]
    struct Oldest {
        marks: String,
    }

    #[derive(serde::Deserialize)]
    struct Middle {
        marks: String,
    }

    impl From<Oldest> for Middle {
        fn from(old: Oldest) -> Self {
            Middle {
                marks: format!("{} oldest->middle", old.marks),
            }
        }
    }

    impl From<Middle> for VaultDoc {
        fn from(old: Middle) -> Self {
            VaultDoc {
                id: format!("{} middle->current", old.marks),
                ..VaultDoc::default()
            }
        }
    }

    impl Legacy for Oldest {
        type Next = Middle;
        const VERSION: u32 = 101;
    }

    impl Legacy for Middle {
        type Next = VaultDoc;
        const VERSION: u32 = 102;
    }

    mod chain {
        use super::{Middle, Oldest};
        use crate::model::vault::VaultDoc;

        schema_chain! {
            current: VaultDoc = crate::VAULT_FORMAT_VERSION,
            102 => Middle,
            101 => Oldest,
        }
    }

    fn payload(version: u32) -> Vec<u8> {
        serde_json::to_vec(&serde_json::json!({ "version": version, "marks": "start" })).unwrap()
    }

    #[test]
    fn the_walk_goes_through_every_step() {
        let doc = chain::upgrade(101, &payload(101), SnapshotFormat::Json).unwrap();
        assert_eq!(doc.id, "start oldest->middle middle->current");
        assert_eq!(doc.version, crate::VAULT_FORMAT_VERSION);

        // One step up: only the last link runs.
        let doc = chain::upgrade(102, &payload(102), SnapshotFormat::Json).unwrap();
        assert_eq!(doc.id, "start middle->current");
    }

    #[test]
    fn a_version_the_listing_does_not_know_is_unsupported() {
        for version in [0, 99, 100, 103, crate::VAULT_FORMAT_VERSION + 1] {
            let err = chain::upgrade(version, &payload(version), SnapshotFormat::Json)
                .expect_err("a version outside the chain must be refused");
            assert!(matches!(err, Error::Unsupported), "{version}: {err:?}");
        }
    }

    #[test]
    fn a_payload_that_does_not_fit_its_own_schema_is_incompatible() {
        let bytes = serde_json::to_vec(&serde_json::json!({ "version": 101 })).unwrap();
        let err = chain::upgrade(101, &bytes, SnapshotFormat::Json)
            .expect_err("a payload without the schema's fields must be refused");
        assert!(matches!(err, Error::IncompatibleVault(_)), "{err:?}");
        assert_eq!(err.code(), "INCOMPATIBLE_VAULT");
    }

    /// The real chain, as `decode_versioned` uses it: the listing covers every
    /// version below the current one, with no gap.
    #[test]
    fn the_real_chain_covers_every_version_below_the_current_one() {
        assert_eq!(
            <super::super::v1::VaultDocV1 as Legacy>::VERSION + 1,
            <super::super::v2::VaultDocV2 as Legacy>::VERSION
        );
        assert_eq!(
            <super::super::v2::VaultDocV2 as Legacy>::VERSION + 1,
            crate::VAULT_FORMAT_VERSION
        );
    }
}
